if (!function_exists('getPermittedCropsSeedList')) {
    /**
     * Standard format for land registration and editing modal dropdowns/chips.
     * Relative icon paths prefixed by $basePrefix (default '../').
     */
    function getPermittedCropsSeedList($basePrefix = '../') {
        $all = getCropsLibrary();
        $list = [];
        $seen = [];
        foreach ($all as $c) {
            // Provide unique entries by value
            if (isset($seen[$c['value']])) continue;
            $seen[$c['value']] = true;
            $list[] = [
                'value' => $c['value'],
                'label' => $c['label'],
                'name' => $c['name'],
                'local_name' => $c['local_name'],
                'category' => $c['category'],
                'category_id' => $c['category_id'],
                'icon' => $basePrefix . $c['icon'],
            ];
        }
        return $list;
    }
}

if (!function_exists('findCropIconUrl')) {
    function findCropIconUrl($cropName, $basePrefix = '../') {
        if (empty($cropName)) {
            return $basePrefix . 'assets/crop-icons/generic-plant/generic-plant.svg';
        }
        $needle = strtolower(trim($cropName));
        $all = getCropsLibrary();
        foreach ($all as $c) {
            if ($needle === strtolower($c['value']) ||
                $needle === strtolower($c['name']) ||
                ($c['local_name'] && $needle === strtolower($c['local_name'])) ||
                strpos(strtolower($c['label']), $needle) !== false ||
                strpos($needle, strtolower($c['value'])) !== false) {
                return $basePrefix . $c['icon'];
            }
        }
        return $basePrefix . 'assets/crop-icons/generic-plant/generic-plant.svg';
    }
}
